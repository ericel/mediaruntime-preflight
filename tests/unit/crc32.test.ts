import { describe, expect, it } from "vitest";

import { Crc32, crc32 } from "../../src/binary/crc32";

const encoder = new TextEncoder();

/** Encode test strings as bytes, independently of the checksum code. */
function bytes(text: string): Uint8Array {
  return encoder.encode(text);
}

describe("CRC-32", () => {
  it("returns zero for empty input", () => {
    expect(crc32(new Uint8Array(0))).toBe(0);
  });

  it("matches the standard 123456789 check value", () => {
    expect(crc32(bytes("123456789"))).toBe(0xcbf43926);
  });

  it("matches the PNG IEND checksum", () => {
    // An empty IEND chunk's checksum covers its four type bytes.
    expect(crc32(bytes("IEND"))).toBe(0xae426082);
  });

  it("matches a binary vector containing every byte value", () => {
    const input = new Uint8Array(256);

    for (let index = 0; index < input.length; index += 1) {
      input[index] = index;
    }

    // Fixed expected value, not generated by the implementation.
    expect(crc32(input)).toBe(0x29058c73);
  });

  it("produces the same known checksum at every split boundary", () => {
    const input = bytes("123456789");

    for (let split = 0; split <= input.length; split += 1) {
      const checksum = new Crc32();

      checksum.update(input.subarray(0, split));
      checksum.update(input.subarray(split));

      expect(checksum.digest()).toBe(0xcbf43926);
    }
  });

  it("supports byte-at-a-time updates", () => {
    const input = bytes("123456789");
    const checksum = new Crc32();

    for (let index = 0; index < input.length; index += 1) {
      checksum.update(input.subarray(index, index + 1));
    }

    expect(checksum.digest()).toBe(0xcbf43926);
  });

  it("processes only the provided view", () => {
    const backing = bytes("xx123456789yy");
    const view = backing.subarray(2, 11);

    expect(crc32(view)).toBe(0xcbf43926);
  });

  it("does not change state when digest is called", () => {
    const checksum = new Crc32();
    checksum.update(bytes("1234"));

    const partial = checksum.digest();

    expect(checksum.digest()).toBe(partial);

    // Reading a digest must not finalize or reset the internal state.
    checksum.update(bytes("56789"));

    expect(checksum.digest()).toBe(0xcbf43926);
  });

  it("ignores empty updates between nonempty updates", () => {
    const checksum = new Crc32();

    checksum.update(bytes("1234"));
    checksum.update(new Uint8Array(0));
    checksum.update(bytes("56789"));

    expect(checksum.digest()).toBe(0xcbf43926);
  });

  it("resets for an independent checksum", () => {
    const checksum = new Crc32();

    checksum.update(bytes("123456789"));
    checksum.reset();

    expect(checksum.digest()).toBe(0);

    checksum.update(bytes("IEND"));

    expect(checksum.digest()).toBe(0xae426082);
  });

  it("keeps separate instances independent", () => {
    const first = new Crc32();
    const second = new Crc32();

    first.update(bytes("1234"));
    second.update(bytes("IEND"));
    first.update(bytes("56789"));

    expect(first.digest()).toBe(0xcbf43926);
    expect(second.digest()).toBe(0xae426082);
  });

  it("does not modify or retain input bytes", () => {
    const input = bytes("123456789");
    const original = input.slice();
    const checksum = new Crc32();

    checksum.update(input);

    expect(input).toEqual(original);

    // Later changes to the input must not affect processed evidence.
    input.fill(0);

    expect(checksum.digest()).toBe(0xcbf43926);
  });
});